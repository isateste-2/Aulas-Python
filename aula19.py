'''
operadores de comparacao
 == (igual)
 != (diferente)
 < (menor)
 > (maior)
 <= (menor ou igual)
 >= (maior ou igual)
'''

maior = 1>5
menor=5<20
maior_ou_igual=10>=10
menor_ou_igual=10<=10
igual=10==10
diferente=10!=10

print(maior)
print(menor)
print(maior_ou_igual)
print(menor_ou_igual)
print(igual)
print(diferente)

