#tipos int e float
#int sao numeros do tipos inteiros
print(11) #int
print(-11) #int
print(0) #int

#float sao numeors do tipos ponto flutuante
print(1.1, 1.3)

#a função type mostra que tipo de argumento é declarado naquela sessao
print (type('isadora')) #resultou em <class 'str'>
print (type(123)) #resultou em <class 'int'>
print (type(12.3)) #resultou em <class 'float'>
print (type(12.3),type(2), type('isa')) #<class 'float'> <class 'int'> <class 'str'>